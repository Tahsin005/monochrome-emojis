#!/usr/bin/env node
/**
 * generate-icon-data.mjs
 *
 * Reads every *.svg from node_modules/lucide-static/icons, extracts the
 * viewBox and all <path d="…"> values, then writes lib/lucide-icons.ts.
 *
 * Usage:
 *   node scripts/generate-icon-data.mjs
 *
 * Output: lib/lucide-icons.ts
 */

import { readdir, readFile, writeFile } from "fs/promises";
import { join, basename } from "path";
import { fileURLToPath } from "url";
import { dirname } from "path";

const __dirname = dirname(fileURLToPath(import.meta.url));

// ── config ───────────────────────────────────────────────────────────────────
// Source: lucide-static ships all SVGs in node_modules — no need to copy them.
const ICONS_DIR = join(__dirname, "..", "node_modules", "lucide-static", "icons");
const OUT_FILE  = join(__dirname, "..", "lib", "lucide-icons.ts");

// ── helpers ──────────────────────────────────────────────────────────────────

/** convert a kebab-case filename (without .svg) to the key used in ICONS. */
function toKey(filename) {
  return basename(filename, ".svg");
}

/** pull the viewBox attribute value from raw SVG text. */
function extractViewBox(svg) {
  const m = svg.match(/viewBox="([^"]+)"/);
  return m ? m[1] : "0 0 24 24";
}

/** extract every <path d="…"> value. */
function extractPaths(svg) {
  const paths = [];
  const re = /\bd="([^"]+)"/gs;
  let m;
  while ((m = re.exec(svg)) !== null) {
    paths.push(m[1].trim());
  }
  return paths;
}

/** escape characters that would break a double-quoted TS string. */
function escapeForTS(str) {
  return str.replace(/\\/g, "\\\\").replace(/"/g, '\\"');
}

// ── main ─────────────────────────────────────────────────────────────────────
async function main() {
  const files = (await readdir(ICONS_DIR))
    .filter((f) => f.endsWith(".svg"))
    .sort();

  console.log(`Found ${files.length} SVG files in ${ICONS_DIR}\n`);

  const entries = [];
  const skipped = [];

  for (const file of files) {
    const svg = await readFile(join(ICONS_DIR, file), "utf8");
    const key = toKey(file);
    const viewBox = extractViewBox(svg);
    const paths = extractPaths(svg);

    if (paths.length === 0) {
      skipped.push(file);
      continue;
    }

    const pathsStr = paths
      .map((p) => `      "${escapeForTS(p)}"`)
      .join(",\n");

    entries.push(
      `  "${key}": {\n    viewBox: "${viewBox}",\n    paths: [\n${pathsStr},\n    ],\n  }`
    );
  }

  if (skipped.length) {
    console.warn(`\n⚠  Skipped ${skipped.length} file(s) with no <path d="…">:`);
    skipped.forEach((f) => console.warn(`   • ${f}`));
    console.warn();
  }

  const output = [
    `// AUTO-GENERATED by scripts/generate-icon-data.mjs`,
    `// Do NOT edit manually – re-run the script to regenerate.`,
    ``,
    `import type { IconDef } from "./emoji-data";`,
    ``,
    `export const LUCIDE_ICONS: Record<string, IconDef> = {`,
    entries.join(",\n"),
    `};`,
    ``,
  ].join("\n");

  await writeFile(OUT_FILE, output, "utf8");
  console.log(`\n✅  Written ${entries.length} icons → ${OUT_FILE}`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
